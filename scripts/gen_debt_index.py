"""Generate the compact open-items index for CLAUDE.md from ``docs/debt.md``.

The single source of truth for a debt entry's status is its ``## N.`` heading
suffix in ``docs/debt.md`` (``— STATUS: OPEN`` / ``— STATUS: PARTIAL (...)`` /
``— RESOLVED <date>`` / ``— SUPERSEDED <date> by #M`` / ``— WONTFIX <date>``).
This script reads those headings and prints the compact open-items index that
lives in CLAUDE.md's "Known Architectural Debt" section, grouped by Tier.

Pure: it only reads ``docs/debt.md`` and prints to stdout. It writes nothing.
Regenerate the CLAUDE.md block with::

    py scripts/gen_debt_index.py

and paste the output verbatim (do not hand-edit the block).
"""

from __future__ import annotations

import pathlib
import re
import sys

DEBT = pathlib.Path(__file__).resolve().parents[1] / "docs" / "debt.md"

# Tier print order + the descriptive label each tier carries in the index.
TIER_ORDER = ["G", "B", "D", "E", "Z"]
TIER_LABEL = {
    "G": "Tier G",
    "B": "Tier B",
    "D": "Tier D",
    "E": "Tier E",
    "Z": "Other (no tier tag in the heading — see body)",
}
DESC_MAX = 34  # characters of the title kept per item, to stay in CLAUDE.md's budget

HEADING = re.compile(r"^## (?P<num>\S+)\. (?P<title>.*) — STATUS: (?P<status>OPEN|PARTIAL)")


def short_desc(title: str) -> str:
    """Trim parentheticals off a heading title and truncate it for the index.

    Parameters
    ----------
    title : str
        The heading text between ``## N. `` and `` — STATUS:``.

    Returns
    -------
    str
        The title with a trailing ``(...)`` parenthetical removed, whitespace
        collapsed, and hard-truncated to ``DESC_MAX`` characters.
    """
    d = re.sub(r"\s*\([^)]*\)\s*$", "", title)
    d = re.sub(r"\s+", " ", d).strip()
    if len(d) > DESC_MAX:
        # cut on a word boundary so the tag never ends mid-word
        d = d[:DESC_MAX].rsplit(" ", 1)[0].rstrip(" —-·+&/,")
    return d


def collect() -> dict[str, list[str]]:
    """Read ``docs/debt.md`` and group OPEN/PARTIAL entries by Tier.

    Returns
    -------
    dict[str, list[str]]
        Tier letter -> list of ``#num desc`` strings, in file order. Entries
        whose heading carries no ``Tier X`` token fall into ``Z`` (Other).
    """
    groups: dict[str, list[str]] = {t: [] for t in TIER_ORDER}
    for line in DEBT.read_text(encoding="utf-8").splitlines():
        m = HEADING.match(line)
        if not m:
            continue
        num, title = m.group("num"), m.group("title")
        tm = re.search(r"Tier ([GBDE])", title)
        tier = tm.group(1) if tm else "Z"
        groups[tier].append(f"#{num} {short_desc(title)}")
    return groups


def render() -> str:
    """Render the full index block (note line + one line per non-empty tier).

    Lines are joined with CRLF and the block carries no trailing newline, so
    the bytes match the CRLF-encoded ``CLAUDE.md`` block exactly.
    """
    groups = collect()
    out = [
        "_Generated by `scripts/gen_debt_index.py` from the `— STATUS:` headings "
        "in [docs/debt.md](docs/debt.md) — do not edit by hand._",
        "",
    ]
    for t in TIER_ORDER:
        if groups[t]:
            out.append(f"**{TIER_LABEL[t]}:** " + " · ".join(groups[t]))
    return "\r\n".join(out)


if __name__ == "__main__":
    # Write raw UTF-8 bytes (CRLF inside render()) so the output is identical on
    # any console codepage and matches the CRLF CLAUDE.md block byte-for-byte.
    sys.stdout.buffer.write(render().encode("utf-8"))

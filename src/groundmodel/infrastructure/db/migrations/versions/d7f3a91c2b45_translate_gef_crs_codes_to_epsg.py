# Declares that ``upgrade()`` rewrites existing user rows (UPDATEs the stored
# CPT geometry SRID + epsg columns from GEF CRS codes to EPSG) so the migrator's
# pre-migration backup step names it among the pending data-rewriting migrations
# (production-readiness audit H2b).
DATA_REWRITE = True

# GEF codelist code → the EPSG code it means. Mirrors
# ``gef_constants.GEF_XY_CODE_TO_EPSG``; kept literal here because a migration
# must reproduce the mapping AS IT WAS when the migration ran, not follow a
# constant that may be extended later.
_XY_CODE_TO_EPSG: dict[int, int] = {32000: 31370, 31000: 28992}

# Vertical, mirroring ``gef_constants.GEF_Z_CODE_TO_EPSG``.
_Z_CODE_TO_EPSG: dict[int, int] = {32001: 5710}


def upgrade() -> None:
    """Re-stamp GEF codelist codes as EPSG codes on every affected CPT row."""
    for gef_code, epsg in _XY_CODE_TO_EPSG.items():
        # Geometry FIRST: it is keyed on the SRID still carried by the row, so
        # it has to run before ``epsg`` is rewritten.
        op.execute(
            f"UPDATE cpt SET location = ST_SetSRID(location, {epsg}) "
            f"WHERE location IS NOT NULL AND ST_SRID(location) = {gef_code}"
        )
        op.execute(f"UPDATE cpt SET epsg = {epsg} WHERE epsg = {gef_code}")

    for gef_code, epsg in _Z_CODE_TO_EPSG.items():
        op.execute(f"UPDATE cpt SET z_epsg = {epsg} WHERE z_epsg = {gef_code}")
        # The elevation-rollback snapshot must travel with it, or clearing a
        # manual elevation edit would restore a GEF-code vertical datum.
        op.execute(f"UPDATE cpt SET original_z_epsg = {epsg} WHERE original_z_epsg = {gef_code}")



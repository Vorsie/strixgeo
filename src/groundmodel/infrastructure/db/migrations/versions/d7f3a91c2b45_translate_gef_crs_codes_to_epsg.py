"""translate stored GEF codelist codes to real EPSG codes

Repairs CPT rows imported from GEF files BEFORE the parser learned that the
number in ``#XYID=`` / ``#ZID=`` is a **GEF codelist code**, not an EPSG code.

The audit finding
-----------------
The parser now translates the GEF code to the EPSG code it means
(``gef_constants.GEF_XY_CODE_TO_EPSG`` / ``GEF_Z_CODE_TO_EPSG``) and keeps the
raw code alongside it in ``xy_code`` / ``z_code``.  That change fixes NEW
imports only.  Nothing repaired the rows already in a database, so a single
project could hold two CRS conventions at once: DOV-imported CPTs tagged 31370,
GEF-imported CPTs tagged 32000 for the *same* physical coordinate system.  Every
EPSG-keyed consumer then treats them as different systems —
``fetch_virtuele_boring_predictions`` silently skips anything that is not 31370,
and the PostGIS ``location`` geometry carries an SRID no spatial query can use.

The mapping (identical to the parser's, by construction)
--------------------------------------------------------
* horizontal ``#XYID`` — ``32000 → 31370`` (Belgian Lambert 72),
  ``31000 → 28992`` (Rijksdriehoeksmeting / RD New)
* vertical ``#ZID`` — ``32001 → 5710`` (mTAW)

The ``location`` geometry's SRID is re-stamped alongside ``epsg``: the column
docstring on ``CptOrm.location`` states it carries "the same SRID as the epsg
column", and leaving the two disagreeing is the bug this migration exists to
close.  ``original_z_epsg`` (the elevation-rollback snapshot) is translated too,
or clearing a manual elevation edit would restore a GEF-code datum.

Why mapping by VALUE is safe here
---------------------------------
None of the three source values is a CRS this application can legitimately have
stored.  32000 and 31000 are not assigned projected CRSs at all.  32001 IS a
real EPSG code (NAD27 / Montana North) — irrelevant to a platform whose data is
Belgian and Dutch, and unreachable through any import path in this codebase.

⚠ This is a DEV-DATABASE REPAIR, not a supported upgrade path.
--------------------------------------------------------------
Backwards compatibility is SUSPENDED pre-ship (owner directive 2026-05-16, see
``docs/backwards-compat.md``), so this migration exists to repair the developer's
own database and any test database, NOT as a contract for external users — there
are none yet.  Re-importing the GEF files produces exactly the same values (see
``docs/parsers-gef.md`` → "Existing rows"), so a wipe-and-re-import is an equally
valid repair.

``downgrade()`` is deliberately a NO-OP: the reverse mapping cannot be applied
safely, because a row reading 31370 after this migration is indistinguishable
from a DOV-imported row that always read 31370, and re-tagging those would break
the rows this migration did not touch.

HAND-WRITTEN, NOT AUTOGENERATED — for the reason recorded in 2244cb54aa1c:
autogenerate proposes a large amount of pre-existing model-vs-database drift
alongside the wanted change, including dropping ``dov_permkey`` indexes the DOV
import relies on.

Revision ID: d7f3a91c2b45
Revises: c5b81d7a4e39
Create Date: 2026-08-03
"""


"""Merge the geo-label twin geotech formation rows (one-time data repair).

Owner ruling 2026-08-31 (debt #278, R3): a body crossing two geological
formations is ONE geotech unit, not two.  Before the find-or-create keys were
narrowed (classified ``(nad_class, source_litho_formation_id)``, skeleton
``(source_litho_formation_id)``), the geotech materialiser forked a SECOND
``geological_formation`` row whenever the same litho unit sat under a different
geological formation — a "geo-label twin".  The dev model grew 22 such groups
(56 redundant rows).  The engine no longer mints twins for NEW bands (the
lookups ``ORDER BY created_at ASC, id ASC`` so the oldest already wins), but the
rows already written stay forked until this repair runs.  The owner accepted
that this migration REWRITES rows he did not touch (R3, verbatim: a one-time
Alembic migration that merges them on upgrade — explicitly NOT
heal-on-next-press).

Design (approved plan D5 — renumber body ordinals, never merge body rows)
------------------------------------------------------------------------
A "twin group" is the set of geotech-minted formations (``source_litho_formation_id
IS NOT NULL``) that share a project + litho parent + NAD class.  The single
window ``PARTITION BY (app_project_id, nad_class, source_litho_formation_id)``
implements BOTH the classified rule (``nad_class`` set) AND the skeleton rule
(``nad_class IS NULL`` — SQL partitions all NULLs together, i.e. by litho parent
alone) because a skeleton row's ``nad_class`` is NULL and a classified row's is
not, so the two never share a partition.

Per group the SURVIVOR is the oldest ``created_at`` (tie-break lowest id).
Every loser's child reference is re-pointed to the survivor BEFORE the loser is
deleted, so the CASCADE FKs (``litho_layer``, ``formation_contact``,
``formation_surface``, ``formation_absence``, ``litho_body_solid``, ``body`` all
CASCADE on ``geological_formation``) never destroy real data.  Unique-key
collisions are resolved per table:

* ``formation_contact`` — the two partial unique indexes ``(model, formation,
  anchor, depth)`` are deduped keeping the survivor's / oldest copy; the rest
  re-point.  (In practice the LL->FC mirror + ``litho_layer`` no-overlap make a
  real collision impossible, so this is defence in depth.)
* ``formation_absence`` — unique ``(formation, kind, investigation)`` deduped
  the same way.
* ``formation_surface`` — unique ``(model, formation)`` deduped the same way.
* ``body`` — unique ``(model, formation, body_ordinal)`` is resolved by
  RENUMBERING, never merging: a two-step high-offset re-rank (bump every
  affected body above the live range, then dense-rank by ``(created_at, id)``)
  dodges the transient unique violations a naive ``+1`` would raise.  NO body
  row is deleted, so ``sample.geotech_body_id`` (no FK) can never be orphaned.
* ``litho_layer`` and ``litho_body_solid`` re-point with a plain UPDATE — the
  former has no formation-scoped unique key, the latter's unique key is
  ``(model, body)`` which a formation re-point does not touch.

Survivor attributes (R2): its ``source_geo_formation_id`` is cleared to NULL (a
kept geo id would be a half-truth post-R1); its ``color_override`` adopts the
oldest loser's non-NULL when the survivor had none; its ``name`` is kept and any
differing loser name is PRINTED (the ``b3c4d5e6f7a8`` rowcount-print precedent).

The two ``litho_layer`` <-> ``formation_contact`` mirror triggers are DISABLED
for the repair window (same guard as ``r2l3m4n5o6p7``): the re-points touch both
mirror tables and the FC dedup DELETEs FCs, either of which the triggers would
otherwise cascade into the paired row.  The repair keeps the mirror pair
consistent itself by re-pointing both sides with the same mapping.

Destructive + one-time.  ``downgrade()`` raises ``NotImplementedError``: the
forked rows carried no information the survivor lacks (same litho parent, same
class), the geo label is a discarded half-truth, and pre-ship backwards-compat
is suspended (owner 2026-05-16).

HAND-WRITTEN, NOT AUTOGENERATED.

Revision ID: a4b5c6d7e8f9
Revises: f3d0a1b2c4e5
Create Date: 2026-09-01
"""


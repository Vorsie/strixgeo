# The body renumber vacates ordinals into a high range no live project reaches
# (a formation never carries a million bodies) before dense-ranking back down.
# int4 max is ~2.1e9, so 1e6 + rn stays well inside range.
_OFFSET = 1_000_000


# ---------------------------------------------------------------------------
# Mirror-trigger toggles — DISABLED for the repair window.
#
# The two mirror triggers differ in scope, verified against the live catalog:
# * ``trg_mirror_litho_layer_to_contact`` (LL->FC) is UNCONDITIONAL — its
#   function body has no model-kind gate, so a geotech-model accepted-layer
#   write mirrors into ``formation_contact`` (this is why the geotech model
#   carries FC rows at all).  Disabling it is load-bearing: without it, the
#   ``repoint_ll`` UPDATE would fire its ``ON CONFLICT DO UPDATE`` and reconcile
#   FC rows mid-repair, fighting the FC dedup.
# * ``trg_mirror_litho_contact_to_layer`` (FC->LL) STILL gates on kind — its
#   body (installed by o9i0j1k2l3m4, unchanged since p0j1k2l3m4n5) opens with
#   ``IF model_kind IS DISTINCT FROM 'lithostratigraphic' THEN RETURN NULL``.
#   For this migration's geotech-only scope it is therefore already a no-op (the
#   FC dedup/re-point touch only geotech-model rows).  We disable it anyway as
#   defense-in-depth — the same guard ``r2l3m4n5o6p7`` used — so the repair is
#   correct even if a future migration widens that trigger's scope.
# ---------------------------------------------------------------------------
_DISABLE_LL_FC = "ALTER TABLE litho_layer DISABLE TRIGGER trg_mirror_litho_layer_to_contact"
_DISABLE_FC_LL = "ALTER TABLE formation_contact DISABLE TRIGGER trg_mirror_litho_contact_to_layer"
_ENABLE_LL_FC = "ALTER TABLE litho_layer ENABLE TRIGGER trg_mirror_litho_layer_to_contact"
_ENABLE_FC_LL = "ALTER TABLE formation_contact ENABLE TRIGGER trg_mirror_litho_contact_to_layer"


# The shared loser->survivor map.  Inlined into every statement (rather than a
# TEMP TABLE) so the async-session migration test can run each statement as its
# own prepared statement without a session-scoped temp object.  ``first_value``
# over the ordered partition returns the oldest row's id (the survivor) for
# every member; ``_merged`` restricts to groups that actually have a loser
# (count > 1) so singletons and non-twin rows are never touched.
_CTE_PREFIX = """WITH _twin_map AS (
    SELECT gf.id AS loser_id,
           first_value(gf.id) OVER (
               PARTITION BY gf.app_project_id, gf.nad_class, gf.source_litho_formation_id
               ORDER BY gf.created_at ASC, gf.id ASC
           ) AS survivor_id
    FROM geological_formation gf
    WHERE gf.source_litho_formation_id IS NOT NULL
),
_merged AS (
    SELECT DISTINCT survivor_id FROM _twin_map WHERE loser_id <> survivor_id
)"""


# R2 — clear the survivor's geo label (a kept geo id is a half-truth post-R1).
_SURVIVOR_GEO_NULL = (
    _CTE_PREFIX
    + """
UPDATE geological_formation s
SET source_geo_formation_id = NULL
FROM _merged
WHERE s.id = _merged.survivor_id
  AND s.source_geo_formation_id IS NOT NULL
"""
)

# R2 — the survivor adopts the OLDEST loser's non-NULL colour when it had none.
_SURVIVOR_COLOR = (
    _CTE_PREFIX
    + """,
_adopt AS (
    SELECT m.survivor_id,
           (SELECT l.color_override
            FROM geological_formation l
            JOIN _twin_map t ON t.loser_id = l.id
            WHERE t.survivor_id = m.survivor_id
              AND l.id <> m.survivor_id
              AND l.color_override IS NOT NULL
            ORDER BY l.created_at ASC, l.id ASC
            LIMIT 1) AS adopted_color
    FROM _merged m
)
UPDATE geological_formation s
SET color_override = _adopt.adopted_color
FROM _adopt
WHERE s.id = _adopt.survivor_id
  AND s.color_override IS NULL
  AND _adopt.adopted_color IS NOT NULL
"""
)

# formation_contact — dedup the two partial unique keys (borehole/cpt anchored)
# across the merged set, keeping the survivor's / oldest copy; synthetic (both
# anchors NULL) contacts are not unique-indexed and are left for the re-point.
_DEDUP_FC = (
    _CTE_PREFIX
    + """,
_dup AS (
    SELECT u.id,
           row_number() OVER (
               PARTITION BY u.model_id, u.survivor_id, u.anchor_id, u.depth_top_m
               ORDER BY u.is_survivor DESC, u.created_at ASC, u.id ASC
           ) AS rn
    FROM (
        SELECT fc.id, fc.model_id, fc.depth_top_m, fc.created_at,
               m.survivor_id,
               COALESCE(fc.borehole_id, fc.cpt_id) AS anchor_id,
               (fc.formation_id = m.survivor_id) AS is_survivor
        FROM formation_contact fc
        JOIN _twin_map m ON m.loser_id = fc.formation_id
        JOIN _merged mm ON mm.survivor_id = m.survivor_id
        WHERE fc.borehole_id IS NOT NULL OR fc.cpt_id IS NOT NULL
    ) u
)
DELETE FROM formation_contact fc
USING _dup
WHERE fc.id = _dup.id AND _dup.rn > 1
"""
)

_REPOINT_FC = (
    _CTE_PREFIX
    + """
UPDATE formation_contact fc
SET formation_id = m.survivor_id
FROM _twin_map m
WHERE fc.formation_id = m.loser_id AND m.loser_id <> m.survivor_id
"""
)

_REPOINT_LL = (
    _CTE_PREFIX
    + """
UPDATE litho_layer ll
SET formation_id = m.survivor_id
FROM _twin_map m
WHERE ll.formation_id = m.loser_id AND m.loser_id <> m.survivor_id
"""
)

# formation_absence — unique (formation, kind, investigation).
_DEDUP_ABSENCE = (
    _CTE_PREFIX
    + """,
_dup AS (
    SELECT u.id,
           row_number() OVER (
               PARTITION BY u.survivor_id, u.investigation_kind, u.investigation_id
               ORDER BY u.is_survivor DESC, u.created_at ASC, u.id ASC
           ) AS rn
    FROM (
        SELECT fa.id, fa.investigation_kind, fa.investigation_id, fa.created_at,
               m.survivor_id,
               (fa.formation_id = m.survivor_id) AS is_survivor
        FROM formation_absence fa
        JOIN _twin_map m ON m.loser_id = fa.formation_id
        JOIN _merged mm ON mm.survivor_id = m.survivor_id
    ) u
)
DELETE FROM formation_absence fa
USING _dup
WHERE fa.id = _dup.id AND _dup.rn > 1
"""
)

_REPOINT_ABSENCE = (
    _CTE_PREFIX
    + """
UPDATE formation_absence fa
SET formation_id = m.survivor_id
FROM _twin_map m
WHERE fa.formation_id = m.loser_id AND m.loser_id <> m.survivor_id
"""
)

# formation_surface — unique (model, formation).
_DEDUP_SURFACE = (
    _CTE_PREFIX
    + """,
_dup AS (
    SELECT u.id,
           row_number() OVER (
               PARTITION BY u.model_id, u.survivor_id
               ORDER BY u.is_survivor DESC, u.created_at ASC, u.id ASC
           ) AS rn
    FROM (
        SELECT fs.id, fs.model_id, fs.created_at,
               m.survivor_id,
               (fs.formation_id = m.survivor_id) AS is_survivor
        FROM formation_surface fs
        JOIN _twin_map m ON m.loser_id = fs.formation_id
        JOIN _merged mm ON mm.survivor_id = m.survivor_id
    ) u
)
DELETE FROM formation_surface fs
USING _dup
WHERE fs.id = _dup.id AND _dup.rn > 1
"""
)

_REPOINT_SURFACE = (
    _CTE_PREFIX
    + """
UPDATE formation_surface fs
SET formation_id = m.survivor_id
FROM _twin_map m
WHERE fs.formation_id = m.loser_id AND m.loser_id <> m.survivor_id
"""
)

# litho_body_solid — unique key is (model, body); a formation re-point never
# collides, so a plain UPDATE.
_REPOINT_SOLID = (
    _CTE_PREFIX
    + """
UPDATE litho_body_solid s
SET formation_id = m.survivor_id
FROM _twin_map m
WHERE s.formation_id = m.loser_id AND m.loser_id <> m.survivor_id
"""
)

# body — step 1 of the renumber: re-point every affected body to the survivor
# formation AND park its ordinal above the live range at a per-group-unique
# temp value.  "Affected" is every body whose formation maps (identity for the
# survivor's own bodies) to a survivor that has losers, so ALL bodies that will
# share the survivor formation move together — nothing is left behind at a low
# ordinal to collide with.
_BODY_BUMP = (
    _CTE_PREFIX
    + f""",
_affected AS (
    SELECT b.id,
           m.survivor_id AS new_formation,
           row_number() OVER (
               PARTITION BY b.model_id, m.survivor_id
               ORDER BY b.created_at ASC, b.id ASC
           ) AS rn
    FROM body b
    JOIN _twin_map m ON m.loser_id = b.formation_id
    JOIN _merged mm ON mm.survivor_id = m.survivor_id
)
UPDATE body b
SET formation_id = _affected.new_formation,
    body_ordinal = {_OFFSET} + _affected.rn
FROM _affected
WHERE b.id = _affected.id
"""
)

# body — step 2: dense-rank the parked bodies back to a contiguous 0-based
# sequence.  Targets [0..n-1] are disjoint from the parked [_OFFSET+rn], so no
# transient unique violation.
_BODY_RERANK = (
    _CTE_PREFIX
    + f""",
_reranked AS (
    SELECT b.id,
           row_number() OVER (
               PARTITION BY b.model_id, b.formation_id
               ORDER BY b.created_at ASC, b.id ASC
           ) - 1 AS new_ordinal
    FROM body b
    JOIN _merged mm ON mm.survivor_id = b.formation_id
    WHERE b.body_ordinal >= {_OFFSET}
)
UPDATE body b
SET body_ordinal = _reranked.new_ordinal
FROM _reranked
WHERE b.id = _reranked.id
"""
)

# Delete the loser formation rows.  Every CASCADE child was re-pointed above;
# the only remaining references are the SET NULL self-FKs (parent_formation_id,
# source_litho_formation_id, source_geo_formation_id) — and a geotech twin is a
# leaf (nothing points its parent/source at it), so those fire for zero rows.
_DELETE_LOSERS = (
    _CTE_PREFIX
    + """
DELETE FROM geological_formation gf
USING _twin_map m
WHERE gf.id = m.loser_id AND m.loser_id <> m.survivor_id
"""
)


# Ordered (label, sql).  The disable/enable bracket the repair; both
# ``upgrade()`` and the migration test iterate this exact list so the tested
# statements ARE the shipped statements.
def _repair_statements() -> list[tuple[str, str]]:
    """Return the ordered ``(label, sql)`` repair statements.

    Returns
    -------
    list[tuple[str, str]]
        Each tuple is a human label and a single SQL statement (no ``;``
        separators — asyncpg rejects multi-command prepared statements), run in
        order inside one transaction.
    """
    return [
        ("disable_ll_fc", _DISABLE_LL_FC),
        ("disable_fc_ll", _DISABLE_FC_LL),
        ("survivor_geo_null", _SURVIVOR_GEO_NULL),
        ("survivor_color", _SURVIVOR_COLOR),
        ("dedup_fc", _DEDUP_FC),
        ("repoint_fc", _REPOINT_FC),
        ("repoint_ll", _REPOINT_LL),
        ("dedup_absence", _DEDUP_ABSENCE),
        ("repoint_absence", _REPOINT_ABSENCE),
        ("dedup_surface", _DEDUP_SURFACE),
        ("repoint_surface", _REPOINT_SURFACE),
        ("repoint_solid", _REPOINT_SOLID),
        ("body_bump", _BODY_BUMP),
        ("body_rerank", _BODY_RERANK),
        ("delete_losers", _DELETE_LOSERS),
        # Fire the DEFERRED litho contiguity constraint before the ALTER TABLE
        # re-enable — Postgres refuses to ALTER a table that has pending deferred
        # trigger events (the repoint_ll UPDATE queued them). The re-point never
        # changed a depth, so the immediate check passes.
        ("constraints_immediate", "SET CONSTRAINTS ALL IMMEDIATE"),
        ("enable_ll_fc", _ENABLE_LL_FC),
        ("enable_fc_ll", _ENABLE_FC_LL),
    ]


# Pre-flight report queries (read-only), following the b3c4d5e6f7a8 print
# precedent. Named so the migration test can execute the SAME SQL against a
# seeded state — a typo surfaces in the test, not first during the real run.
_COUNT_LOSERS_SQL = _CTE_PREFIX + "\nSELECT count(*) FROM _twin_map WHERE loser_id <> survivor_id"
_COUNT_GROUPS_SQL = _CTE_PREFIX + "\nSELECT count(*) FROM _merged"
_NAME_DIFF_SQL = (
    _CTE_PREFIX
    + """
SELECT s.id, s.name AS survivor_name, l.name AS loser_name
FROM _twin_map t
JOIN geological_formation s ON s.id = t.survivor_id
JOIN geological_formation l ON l.id = t.loser_id
WHERE t.loser_id <> t.survivor_id
  AND l.name IS DISTINCT FROM s.name
"""
)


def upgrade() -> None:
    """Merge every geo-label twin group into its oldest survivor."""
    bind = op.get_bind()

    # Pre-state report (read-only).
    losers = bind.exec_driver_sql(_COUNT_LOSERS_SQL).scalar()
    groups = bind.exec_driver_sql(_COUNT_GROUPS_SQL).scalar()
    print(f"  [migration a4b5c6d7e8f9] {groups} twin group(s), {losers} loser row(s) to merge")

    # Differing loser names — the survivor keeps its own name; surface the rest.
    name_rows = bind.exec_driver_sql(_NAME_DIFF_SQL).fetchall()
    for row in name_rows:
        print(
            f"  [migration a4b5c6d7e8f9] survivor {row[0]} keeps name "
            f"{row[1]!r}; dropped loser name {row[2]!r}"
        )

    for label, sql in _repair_statements():
        result = bind.exec_driver_sql(sql)
        if label.startswith(("survivor", "dedup", "repoint", "body", "delete")):
            print(f"  [migration a4b5c6d7e8f9] {label}: {result.rowcount} row(s)")


def downgrade() -> None:
    """Irreversible — the forked geo-label rows carried no unique information.

    Raises
    ------
    NotImplementedError
        Always. The losers held the same litho parent + NAD class as the
        survivor and a geo label that R1 discards; there is nothing to restore,
        and pre-ship backwards-compat is suspended (owner 2026-05-16).
    """
    raise NotImplementedError(
        "a4b5c6d7e8f9 is a destructive one-time geo-label twin merge; no downgrade."
    )

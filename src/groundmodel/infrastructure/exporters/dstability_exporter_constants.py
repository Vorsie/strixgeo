"""Constants for the D-Stability (``.stix``) section exporter.

Two groups live here: the geometry tolerances that decide whether a
region of the 2-D partition is drawable at all, and the fixed strings
the artefact carries so an engineer reading the file in D-Stability
knows what Strix did and did not state.

Absent-parameter representation (audit 2026-09-02)
--------------------------------------------------
When a unit's NAD class is NOT in ``NAD_SOIL_PARAMETERS`` (the shipped
state — the table is empty until the owner fills it), the exporter adds
the soil with name + code only and writes NO parameter. GEOLib then
leaves its own initial values, which are the honest "blank": cohesion,
friction angle and both unit weights are **0**. Two defaults GEOLib
forces that Strix does NOT choose, and that stay in place on the absent
path (they only matter once the engineer parameterises the soil):
``ShearStrengthModelTypeBelowPhreaticLevel = Su`` (not Mohr-Coulomb),
and ``SuShearStrengthModel.StrengthIncreaseExponent = 1.0``. GEOLib CAN
express "no model" (``ShearStrengthModelTypePhreaticLevel.NONE``), but
the absent path deliberately does not set it — the zeros are already the
unmistakable blank, and forcing NONE would change dogfed behaviour. When
parameters ARE present the exporter sets Mohr-Coulomb on both sides, so
the ``Su``-below default no longer applies.
"""

from __future__ import annotations

# Smallest polygon area (m²) we hand to GEOLib. Below it the ring is a
# line, and GEOLib's shapely ``make_valid`` collapses it to a
# MultiLineString that ``to_dstability_points`` rejects with an opaque
# ValueError. Matched to the 2-D engine's own zero-area floor (1e-9 m²,
# debt #228 "litho engine slivers") so a region the editor considers
# real is never dropped here.
MIN_POLYGON_AREA_M2 = 1e-9

# Minimum distinct vertices for a ring to enclose an area at all.
MIN_POLYGON_POINTS = 3

# ``projectinfo.Remarks`` — the liability line, stated inside the
# artefact rather than only in our docs, because the file outlives the
# conversation that produced it.
STIX_REMARKS = (
    "Generated by StrixGeo. Geometry and soil identification come from the "
    "cross-section as drawn. Soil PARAMETERS are NOT exported: every strength, "
    "stiffness and unit-weight field is left at the D-Stability default and "
    "must be filled in by the engineer. No phreatic line, load or "
    "reinforcement is exported."
)

# ``projectinfo.LastModifier`` — names the producer so a reviewer can
# tell a Strix-generated geometry from a hand-drawn one.
STIX_LAST_MODIFIER = "StrixGeo"

# Layer note template. The layer's own Label carries the display name;
# the note carries the machine identity a downstream script keys on,
# including the formation id that resolves a (class, soil) collision.
LAYER_NOTE_TEMPLATE = (
    "Strix unit: {name} | NAD class: {nad_class} | Soil: {soil_code} | "
    "Strix formation id: {formation_id} | CPT-derived estimate — design "
    "parameters not exported"
)

# Rendered in the note wherever the unit carries no such identifier.
NOTE_ABSENT = "n/a"

"""The database ERD in docs/erd.md stays in step with the ORM metadata.

The rule: ``docs/erd.md`` is generated by ``scripts/gen_erd.py`` from
``Base.metadata`` and is never edited by hand. When a model changes and the
file is not regenerated, this test fails and names the command that fixes it.
The diagram must also parse in GitHub's Mermaid renderer, so every line of a
diagram block must match Mermaid's ``erDiagram`` grammar.
"""

from __future__ import annotations

import importlib.util
import re
import sys
from pathlib import Path
from types import ModuleType

import pytest
from sqlalchemy import Column, ForeignKey, Integer, MetaData, String, Table

_REPO = Path(__file__).resolve().parents[3]
_SCRIPT = _REPO / "scripts" / "gen_erd.py"


def _load_generator() -> ModuleType:
    spec = importlib.util.spec_from_file_location("_gen_erd", _SCRIPT)
    assert spec is not None and spec.loader is not None, f"missing {_SCRIPT}"
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


@pytest.fixture(scope="module")
def gen() -> ModuleType:
    return _load_generator()


@pytest.fixture(scope="module")
def erd_text(gen: ModuleType) -> str:
    path: Path = gen.ERD_PATH
    assert path.is_file(), f"{path} is missing. Generate it with: {gen.REGENERATE_COMMAND}"
    return path.read_text(encoding="utf-8")


def _diagram_lines(text: str) -> list[list[str]]:
    """Return the lines of every ```mermaid block, one list per block."""
    blocks: list[list[str]] = []
    current: list[str] | None = None
    for line in text.split("\n"):
        if line.strip() == "```mermaid":
            current = []
        elif line.strip() == "```" and current is not None:
            blocks.append(current)
            current = None
        elif current is not None:
            current.append(line)
    return blocks


# --- staleness: the file is exactly what the generator emits today ----------


def test_erd_file_matches_fresh_output_from_the_orm_metadata(
    gen: ModuleType, erd_text: str
) -> None:
    fresh = gen.render_erd(gen.load_metadata())
    assert erd_text == fresh, (
        "docs/erd.md is stale: the ORM models changed but the ERD was not "
        f"regenerated. Run: {gen.REGENERATE_COMMAND}"
    )


def test_every_orm_table_is_drawn_with_its_columns_exactly_once(
    gen: ModuleType, erd_text: str
) -> None:
    metadata = gen.load_metadata()
    drawn = re.findall(r"^\s+([A-Za-z_][A-Za-z0-9_]*) \{$", erd_text, flags=re.MULTILINE)
    assert len(drawn) == len(metadata.tables)
    assert sorted(drawn) == sorted(metadata.tables)


def test_every_table_belongs_to_one_readable_group(gen: ModuleType) -> None:
    metadata = gen.load_metadata()
    unplaced = sorted(set(metadata.tables) - set(gen.TABLE_GROUPS))
    assert not unplaced, f"add these tables to TABLE_GROUPS in scripts/gen_erd.py: {unplaced}"
    stale = sorted(set(gen.TABLE_GROUPS) - set(metadata.tables))
    assert not stale, f"TABLE_GROUPS names tables that no longer exist: {stale}"
    assert set(gen.TABLE_GROUPS.values()) == set(gen.GROUP_ORDER)
    for group in gen.GROUP_ORDER:
        size = sum(1 for g in gen.TABLE_GROUPS.values() if g == group)
        assert size <= gen.MAX_GROUP_SIZE, f"group {group!r} has {size} tables"


# --- grammar: every diagram line is valid Mermaid erDiagram syntax -----------

_NAME = r"[A-Za-z_][A-Za-z0-9_]*"
_GRAMMAR = [
    re.compile(r"^erDiagram$"),
    # entity with attributes: `    table {` ... `    }`
    re.compile(rf"^    {_NAME} \{{$"),
    re.compile(r"^    \}$"),
    # attribute: `type name [PK|FK|UK[,..]] ["comment"]` (no spaces/brackets in type)
    re.compile(rf'^        [A-Za-z][A-Za-z0-9_]* {_NAME}( (PK|FK|UK)(,(PK|FK|UK))*)?( "[^"]*")?$'),
    # bare entity declaration (overview diagram)
    re.compile(rf"^    {_NAME}$"),
    # relationship: `child }o--|| parent : "label"`
    re.compile(rf'^    {_NAME} (\|o|\|\||\}}o|\}}\|)--(o\||\|\||o\{{|\|\{{) {_NAME} : "[^"]*"$'),
]


def test_every_diagram_line_matches_the_mermaid_er_grammar(erd_text: str) -> None:
    blocks = _diagram_lines(erd_text)
    assert blocks, "docs/erd.md holds no ```mermaid block"
    bad = [
        line
        for block in blocks
        for line in block
        if line.strip() and not any(p.match(line) for p in _GRAMMAR)
    ]
    assert not bad, f"lines GitHub's Mermaid renderer would reject: {bad[:10]}"
    for block in blocks:
        assert block[0] == "erDiagram"


def test_output_uses_lf_line_endings_only(gen: ModuleType) -> None:
    assert "\r" not in gen.render_erd(gen.load_metadata())


# --- cardinality follows nullability and uniqueness of the FK column ---------


def _toy_metadata() -> MetaData:
    md = MetaData()
    Table("parent", md, Column("id", Integer, primary_key=True))
    Table(
        "child",
        md,
        Column("id", Integer, primary_key=True),
        Column("opt_parent_id", ForeignKey("parent.id"), nullable=True),
        Column("req_parent_id", ForeignKey("parent.id"), nullable=False),
        Column("one_parent_id", ForeignKey("parent.id"), nullable=True, unique=True),
        Column("sole_parent_id", ForeignKey("parent.id"), nullable=False, unique=True),
        Column("label", String(200), nullable=True),
    )
    return md


# Standard crow's foot: a parent may have no children, so the child side is
# zero-or-many (`}o`) unless the FK column is unique (`|o`). The parent side
# says how many parents a child row has: NOT NULL -> exactly one (`||`),
# nullable -> zero or one (`o|`).


def test_a_non_null_fk_is_zero_or_many_to_exactly_one(gen: ModuleType) -> None:
    lines = gen.relationship_lines(_toy_metadata().tables.values())
    assert '    child }o--|| parent : "req_parent_id"' in lines


def test_a_nullable_fk_is_zero_or_many_to_zero_or_one(gen: ModuleType) -> None:
    lines = gen.relationship_lines(_toy_metadata().tables.values())
    assert '    child }o--o| parent : "opt_parent_id"' in lines


def test_a_unique_non_null_fk_is_zero_or_one_to_exactly_one(gen: ModuleType) -> None:
    lines = gen.relationship_lines(_toy_metadata().tables.values())
    assert '    child |o--|| parent : "sole_parent_id"' in lines


def test_a_unique_nullable_fk_is_zero_or_one_to_zero_or_one(gen: ModuleType) -> None:
    lines = gen.relationship_lines(_toy_metadata().tables.values())
    assert '    child |o--o| parent : "one_parent_id"' in lines


def test_types_are_sanitised_for_mermaid(gen: ModuleType) -> None:
    child = _toy_metadata().tables["child"]
    assert gen.mermaid_type(child.c.label.type) == "varchar200"


# --- the --check flag ---------------------------------------------------------


def test_check_flag_fails_on_a_stale_file_and_passes_on_a_fresh_one(
    gen: ModuleType, tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    target = tmp_path / "erd.md"
    target.write_text("stale\n", encoding="utf-8")
    assert gen.main(["--check", "--output", str(target)]) == 1
    assert gen.REGENERATE_COMMAND in capsys.readouterr().err
    assert gen.main(["--output", str(target)]) == 0
    assert gen.main(["--check", "--output", str(target)]) == 0
